import test from "node:test";
import assert from "node:assert/strict";
import {
 REACTIVE_FORMAT,REACTIVE_ORIGIN,MAX_REACTIVE_PENDING,MAX_REACTIVE_RUNS,
 validateReactionEvent,validateReactionRule,restoreReactionRules,ReactiveCoordinator
} from "../../adamantium/construct-native/reactor.mjs";
const rule=(id="rx",more={})=>({
 id,event:"nodes:add",whenType:"inject",presetId:"catch_debug",
 enabled:true,cleanup:true,maxPerFlow:2,...more
});
const event=(nodeId="node_1",more={})=>({
 event:"nodes:add",flowId:"flow_1",nodeId,nodeType:"inject",origin:"palette",...more
});
test("reactions are opt-in, versioned, and disabled on reload",()=>{
 const x=new ReactiveCoordinator();
 assert.equal(x.enabledCount(),0);
 x.addRule(rule());
 assert.equal(x.enabledCount(),1);
 const raw=x.rulesSnapshot();
 assert.equal(raw.format,REACTIVE_FORMAT);
 const restored=restoreReactionRules(raw);
 assert.equal(restored.rules.length,1);
 assert.equal(restored.rules[0].enabled,false);
 assert.equal(new ReactiveCoordinator(raw).enabledCount(),0);
 assert.throws(()=>validateReactionRule(rule("bad",{presetId:"exec"})),/preset ID/);
 assert.throws(()=>validateReactionRule(rule("bad",{whenType:"http request"})),/trigger type/);
 assert.throws(()=>validateReactionRule(rule("bad",{maxPerFlow:999})),/flow limit/);
 assert.throws(()=>restoreReactionRules({format:REACTIVE_FORMAT,rules:[rule(),rule()]}),/duplicate reaction ID/);
});
test("event on native palette node enqueues bounded build with ownership receipt",()=>{
 const x=new ReactiveCoordinator();x.addRule(rule());
 assert.equal(x.accept(event()).enqueued,1);
 assert.equal(x.accept(event()).enqueued,0,"same event ID cannot create twice");
 assert.equal(x.status().queued,1);
 const plan=x.next();
 assert.equal(plan.action,"build");
 assert.equal(plan.presetId,"catch_debug");
 assert.equal(x.next(),null,"serial transaction lock");
 const r=x.complete(plan.id,{success:true,nodeIds:["generated_1","generated_2"]});
 assert.equal(r.success,true);
 assert.deepEqual(x.getOwned("flow_1","node_1","rx").nodeIds,["generated_1","generated_2"]);
 assert.equal(x.status().ownership,1);
});
test("mutations generated by Construct never recursively trigger Construct",()=>{
 const x=new ReactiveCoordinator();x.addRule(rule());
 assert.equal(x.accept(event("generated_1",{origin:REACTIVE_ORIGIN})).reason,"own-origin");
 assert.equal(x.accept(event("generated_1",{origin:REACTIVE_ORIGIN+":rx"})).reason,"own-origin");
 assert.equal(x.status().queued,0);
});
test("cleanup is possible only for tracked, explicitly owned generated nodes",()=>{
 const x=new ReactiveCoordinator();x.addRule(rule());
 assert.equal(x.accept(event("user_input")).enqueued,1);
 const plan=x.next();
 x.complete(plan.id,{success:true,nodeIds:["owned_a","owned_b"]});
 assert.equal(x.accept(event("untracked",{event:"nodes:remove"})).enqueued,0);
 const cleanup=x.accept(event("user_input",{event:"nodes:remove"}));
 assert.equal(cleanup.enqueued,1);
 const next=x.next();
 assert.equal(next.action,"cleanup");
 assert.equal(next.sourceId,"user_input");
 // Failed cleanup must not delete ownership; UI can diagnose and leave nodes alone.
 x.complete(next.id,{success:false});
 assert.ok(x.getOwned("flow_1","user_input","rx"));
 assert.equal(x.accept(event("user_input",{event:"nodes:remove"})).enqueued,0,"do not loop failed cleanup");
});
test("non-allowlisted events, malformed origins and unsupported trigger types fail closed",()=>{
 assert.throws(()=>validateReactionEvent(event("id",{event:"runtime:deploy"})),/unsupported event/);
 assert.throws(()=>validateReactionEvent(event("id",{nodeType:"exec"})),/untrusted node type/);
 assert.throws(()=>validateReactionEvent(event("id",{flowId:"../../bad"})),/flow ID/);
 assert.throws(()=>validateReactionEvent(event("id",{origin:{}})),/event origin/);
});
test("max-per-flow and flow independence are enforced for automatic construction",()=>{
 const x=new ReactiveCoordinator();x.addRule(rule("r1",{maxPerFlow:1}));
 assert.equal(x.accept(event("first")).enqueued,1);
 assert.equal(x.accept(event("second")).enqueued,0,"one pending action reaches rule flow quota");
 const first=x.next();x.complete(first.id,{success:true,nodeIds:["n1","n2"]});
 assert.equal(x.accept(event("third")).enqueued,0,"already constructed assembly reaches quota");
 assert.equal(x.accept(event("first_other",{flowId:"flow_2"})).enqueued,1);
});
test("different rules are isolated; deleting a rule leaves generated nodes untouched",()=>{
 const x=new ReactiveCoordinator();
 x.addRule(rule("x",{cleanup:false}));
 x.addRule(rule("y",{presetId:"change_debug"}));
 assert.equal(x.accept(event()).enqueued,2);
 const a=x.next();x.complete(a.id,{success:true,nodeIds:["a","b"]});
 const b=x.next();x.complete(b.id,{success:true,nodeIds:["c","d"]});
 x.removeRule("x");
 assert.ok(x.getOwned("flow_1","node_1","x"));
 assert.equal(x.accept(event("node_1",{event:"nodes:remove"})).enqueued,1,"only cleanup-enabled retained rule");
 const cleanup=x.next();assert.equal(cleanup.ruleId,"y");
 x.complete(cleanup.id,{success:true});
 assert.equal(x.getOwned("flow_1","node_1","y"),null);
 assert.ok(x.getOwned("flow_1","node_1","x"));
});
test("explicit disabling blocks new events, and no source-less build can occur",()=>{
 const x=new ReactiveCoordinator();x.addRule(rule());
 x.setEnabled("rx",false);
 assert.equal(x.accept(event()).enqueued,0);
 assert.equal(x.next(),null);
 assert.throws(()=>x.complete("does_not_exist",{success:true,nodeIds:[]}),/matching active/);
});
test("untrusted source cannot extend pending queue beyond cap",()=>{
 const x=new ReactiveCoordinator();
 for(let i=0;i<MAX_REACTIVE_PENDING+5;i++)x.addRule(rule("r"+i,{maxPerFlow:4}));
 const first=x.accept(event());
 assert.equal(first.enqueued,MAX_REACTIVE_PENDING);
 assert.equal(x.status().queued,MAX_REACTIVE_PENDING);
});
test("failed build is recorded without owning foreign nodes, and never retried automatically",()=>{
 const x=new ReactiveCoordinator();x.addRule(rule());
 x.accept(event());
 const plan=x.next();x.complete(plan.id,{success:false});
 assert.equal(x.getOwned("flow_1","node_1","rx"),null);
 assert.equal(x.accept(event()).enqueued,0);
 assert.equal(x.status().started,1);
});
