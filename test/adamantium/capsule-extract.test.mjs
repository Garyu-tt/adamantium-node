import test from "node:test";
import assert from "node:assert/strict";
import {CapsuleStudio} from "../../adamantium/capsule-studio.mjs";
import {extractSelection,CapsuleTemplateLibrary} from "../../adamantium/capsule-extract.mjs";
const port=(tag,direction)=>({tag,direction,dataType:"core.json@1",semantics:"data"});
const make=()=>{
 const studio=new CapsuleStudio(),root=studio.createGraph("Root");
 const def=studio.createDefinition({name:"JSON processor",language:"python",source:"def run(x): return x",ports:[port("data","input"),port("result","output")]});
 return {studio,root,def};
};
test("extract selection rewrites cross edges without duplicating code or losing IDs",()=>{
 const {studio,root,def}=make();
 const a=studio.place(root,def.id),b=studio.place(root,def.id),c=studio.place(root,def.id),d=studio.place(root,def.id);
 const left=studio.connect(root,{fromId:a,fromTag:"result",toId:b,toTag:"data"});
 const middle=studio.connect(root,{fromId:b,fromTag:"result",toId:c,toTag:"data"});
 const right=studio.connect(root,{fromId:c,fromTag:"result",toId:d,toTag:"data"});
 const result=extractSelection(studio,root,[b,c],"Subprocess");
 const parent=studio.graph(root),inner=studio.graph(result.graphId);
 assert.equal(parent.instances.length,3);
 assert.equal(inner.instances.length,2);
 assert.equal(inner.edges.length,1);
 assert.equal(inner.edges[0].id,middle);
 assert.equal(parent.edges.length,2);
 assert.deepEqual(new Set(parent.edges.map(e=>e.id)),new Set([left,right]));
 assert.equal(result.interfacePorts,2);
 assert.equal(inner.boundary.find(p=>p.direction==="input").side,"west");
 assert.equal(inner.boundary.find(p=>p.direction==="output").side,"east");
 assert.equal(parent.edges[0].toId,result.instanceId);
 assert.equal(parent.edges[1].fromId,result.instanceId);
 assert.deepEqual(CapsuleStudio.restore(studio.snapshot()).snapshot(),studio.snapshot());
});
test("fan-out from one internal output uses one tagged external port, retaining distinct outside wires",()=>{
 const {studio,root,def}=make();
 const a=studio.place(root,def.id),b=studio.place(root,def.id),c=studio.place(root,def.id);
 studio.connect(root,{fromId:a,fromTag:"result",toId:b,toTag:"data"});
 studio.connect(root,{fromId:a,fromTag:"result",toId:c,toTag:"data"});
 const r=extractSelection(studio,root,[a],"Only A");
 assert.equal(r.interfacePorts,1);
 assert.equal(studio.graph(root).edges.length,2);
 assert.equal(studio.graph(root).edges[0].fromTag,studio.graph(root).edges[1].fromTag);
});
test("invalid selection rolls back atomically",()=>{
 const {studio,root,def}=make();
 const a=studio.place(root,def.id),b=studio.place(root,def.id);
 const old=studio.snapshot();
 assert.throws(()=>extractSelection(studio,root,[a,"missing"],"No"),/missing/);
 assert.deepEqual(studio.snapshot(),old);
 assert.throws(()=>extractSelection(studio,root,[a,a],"No"),/duplicate/);
 assert.deepEqual(studio.snapshot(),old);
});
test("recursive capsule extraction rebinds existing child parent",()=>{
 const {studio,root,def}=make();
 const capsule=studio.createCapsule(root,"Existing");
 const inner=studio.place(capsule.graphId,def.id);
 studio.expose(capsule.graphId,{side:"east",instanceId:inner,tag:"result",externalTag:"out"});
 const other=studio.place(root,def.id);
 studio.connect(root,{fromId:capsule.instanceId,fromTag:"out",toId:other,toTag:"data"});
 const r=extractSelection(studio,root,[capsule.instanceId],"Outer");
 assert.equal(studio.graph(capsule.graphId).parent.graphId,r.graphId);
 assert.equal(studio.path(capsule.graphId).length,3);
 assert.equal(CapsuleStudio.restore(studio.snapshot()).path(capsule.graphId).length,3);
});
test("template capture and repeated placement create independent children with shared definitions",()=>{
 const {studio,root,def}=make();
 const capsule=studio.createCapsule(root,"Pipe");
 const n=studio.place(capsule.graphId,def.id);
 studio.expose(capsule.graphId,{side:"east",instanceId:n,tag:"result",externalTag:"output"});
 const lib=new CapsuleTemplateLibrary();
 const first=lib.capture(studio,capsule.graphId,"Reusable pipe");
 const again=lib.capture(studio,capsule.graphId,"Another title");
 assert.deepEqual(again,{id:first.id,reused:true});
 const a=lib.place(studio,root,first.id),b=lib.place(studio,root,first.id);
 assert.notEqual(a.graphId,b.graphId);
 assert.equal(lib.palette("pipe")[0].used,2);
 assert.equal(Object.keys(studio.definitions).length,1);
 assert.notEqual(studio.graph(a.graphId).instances[0].id,studio.graph(b.graphId).instances[0].id);
 assert.deepEqual(studio.graph(a.graphId).boundary.map(p=>p.tag),["output"]);
 assert.deepEqual(studio.graph(b.graphId).boundary.map(p=>p.tag),["output"]);
 assert.deepEqual(CapsuleStudio.restore(studio.snapshot()).snapshot(),studio.snapshot());
});
test("templates preserve recursive nested capsules and typed external ports",()=>{
 const {studio,root,def}=make();
 const outer=studio.createCapsule(root,"Outer");
 const child=studio.createCapsule(outer.graphId,"Child");
 const n=studio.place(child.graphId,def.id);
 studio.expose(child.graphId,{side:"east",instanceId:n,tag:"result",externalTag:"output"});
 studio.expose(outer.graphId,{side:"north",instanceId:child.instanceId,tag:"output",externalTag:"northout"});
 const lib=new CapsuleTemplateLibrary(),tpl=lib.capture(studio,outer.graphId,"Nested template");
 const duplicate=lib.place(studio,root,tpl.id);
 const duplicatedChild=studio.graph(duplicate.graphId).instances[0];
 assert.equal(studio.graph(duplicate.graphId).boundary[0].tag,"northout");
 assert.equal(studio.graph(duplicatedChild.childGraphId).boundary[0].tag,"output");
 assert.deepEqual(CapsuleTemplateLibrary.restore(lib.snapshot()).snapshot(),lib.snapshot());
});
test("template import rejects tampered fingerprints; missing definitions block placement",()=>{
 const {studio,root,def}=make();
 const c=studio.createCapsule(root,"C");studio.place(c.graphId,def.id);
 const lib=new CapsuleTemplateLibrary(),{id}=lib.capture(studio,c.graphId,"Reusable");
 const saved=lib.snapshot();
 saved.templates[id].graph.nodes[0].version=999;
 assert.throws(()=>CapsuleTemplateLibrary.restore(saved),/fingerprint/);
 const good=CapsuleTemplateLibrary.restore(lib.snapshot());
 delete studio.definitions[def.id];
 const before=studio.snapshot();
 assert.throws(()=>good.place(studio,root,id),/definition/);
 assert.deepEqual(studio.snapshot(),before);
});

test("extracting an entire graph is a valid zero-boundary capsule",()=>{
 const {studio,root,def}=make();
 const a=studio.place(root,def.id),b=studio.place(root,def.id);
 studio.connect(root,{fromId:a,fromTag:"result",toId:b,toTag:"data"});
 const extracted=extractSelection(studio,root,[a,b],"Entire graph");
 assert.equal(extracted.interfacePorts,0);
 assert.equal(studio.graph(root).instances.length,1);
 assert.equal(studio.graph(extracted.graphId).instances.length,2);
 assert.equal(studio.graph(extracted.graphId).edges.length,1);
});
