// R05 durable agent-factory proposal and proof. No privileged MAS execution.
import {DurableFactoryLedger, factoryDigest} from './durable-ledger.mjs';
import {renderNodePackage} from './generate.mjs';
import {factoryToUniversalGraph} from './g0-projection.mjs';
import {verifyIsolatedFactory} from '../agent-gateway/factory-verify.mjs';

const fail=code=>{throw Object.assign(new Error(code),{code});};
const proposalId=contract=>'candidate-'+factoryDigest(JSON.stringify(contract)).slice(7,39);
const ensureCAS=(state,expectedSequence,expectedHead)=>{
 if(state.sequence!==expectedSequence||state.head!==expectedHead)
  fail('revision_conflict');
};
export class DurableFactoryWorkflow{
 constructor(ledger,{runner=verifyIsolatedFactory}={}){
  this.ledger=ledger;this.runner=runner;this.active=false;
 }
 static async create(root,options){
  return new DurableFactoryWorkflow(await DurableFactoryLedger.create(root),options);
 }
 static async open(root,options){
  return new DurableFactoryWorkflow(await DurableFactoryLedger.open(root,options),options);
 }
 async inspect(options){return this.ledger.inspect(options);}
 async propose({contract,expectedSequence,expectedHead}){
  const rendered=renderNodePackage(contract);
  const id=proposalId(rendered.contract);
  const before=await this.inspect();
  const previous=before.proposals[id];
  if(previous){
   if(JSON.stringify(previous.contract)!==JSON.stringify(rendered.contract))
    fail('idempotency_payload_conflict');
   return {proposalId:id,replayed:true,status:previous.status,
    sequence:before.sequence,head:before.head,publicationAllowed:false};
  }
  ensureCAS(before,expectedSequence,expectedHead);
  const receipt=await this.ledger.append({
   kind:'factory.proposed',payload:{
    proposalId:id,contract:rendered.contract,
    sourceDigest:factoryDigest(JSON.stringify(rendered.sha256))
   },
   expectedSequence,expectedHead
  });
  return {...receipt,replayed:false,graphPreview:factoryToUniversalGraph(rendered.contract)};
 }
 async verify({proposalId:id,expectedSequence,expectedHead}){
  if(this.active)fail('factory_verification_busy');
  const before=await this.inspect();
  const proposal=before.proposals[id];
  if(!proposal)fail('proposal_not_found');
  if(proposal.status==='verified')return {
   proposalId:id,replayed:true,status:'verified',
   sequence:before.sequence,head:before.head,
   verificationDigest:proposal.verificationDigest,productionWrite:false
  };
  if(proposal.status!=='proposed')fail('candidate_not_pending');
  ensureCAS(before,expectedSequence,expectedHead);
  this.active=true;
  try{
   const proof=await this.runner(proposal.contract);
   // The strict ledger validator compares this proof with the generated bytes
   // and refuses incomplete / fake success receipts.
   return await this.ledger.append({
    kind:'factory.verified',payload:{
     proposalId:id,verificationDigest:factoryDigest(JSON.stringify(proof)),proof
    },expectedSequence,expectedHead
   });
  }finally{this.active=false;}
 }
 async requestPromotion({proposalId:id,expectedSequence,expectedHead}){
  const before=await this.inspect();
  const proposal=before.proposals[id];
  if(!proposal)fail('proposal_not_found');
  if(proposal.promotionRequested)return {proposalId:id,replayed:true,
   sequence:before.sequence,head:before.head,approvalEffective:false};
  if(proposal.status!=='verified')fail('promotion_requires_verified_proof');
  ensureCAS(before,expectedSequence,expectedHead);
  return this.ledger.append({
   kind:'factory.promotion.requested',payload:{
    proposalId:id,approvalEffect:false
   },expectedSequence,expectedHead
  });
 }
 async preview(id){
  const state=await this.inspect();
  const proposal=state.proposals[id];
  if(!proposal)fail('proposal_not_found');
  return {schema:'adamantium.factory.projection/1',
   graph:factoryToUniversalGraph(proposal.contract),
   proposalStatus:proposal.status,ledgerSequence:state.sequence,
   ledgerHead:state.head,validatedWithNativeG0Compiler:false,
   executionAuthorized:false,productionInstalled:false};
 }
}
